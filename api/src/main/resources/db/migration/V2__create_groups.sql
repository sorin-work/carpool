create table carpool_groups (
    id          bigint generated by default as identity primary key,
    name        varchar(80)  not null,
    description varchar(500),
    invite_code varchar(12)  not null,
    timezone    varchar(64)  not null,
    created_at  timestamp with time zone not null,
    constraint uq_groups_invite_code unique (invite_code)
);

create table group_members (
    id        bigint generated by default as identity primary key,
    group_id  bigint      not null references carpool_groups (id) on delete cascade,
    user_id   bigint      not null references users (id) on delete cascade,
    role      varchar(16) not null,
    joined_at timestamp with time zone not null,
    constraint uq_group_members unique (group_id, user_id)
);

create index ix_group_members_user on group_members (user_id);
