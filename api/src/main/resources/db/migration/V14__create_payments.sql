-- Money members paid each other outside the app to settle fuel costs.
create table payments (
    id             bigint generated by default as identity primary key,
    group_id       bigint      not null references carpool_groups (id) on delete cascade,
    from_member_id bigint      not null references group_members (id) on delete cascade,
    to_member_id   bigint      not null references group_members (id) on delete cascade,
    amount_cents   bigint      not null,
    paid_on        date        not null,
    recorded_by    bigint      not null references group_members (id) on delete cascade,
    created_at     timestamp with time zone not null,
    constraint ck_payments_amount check (amount_cents > 0)
);

create index ix_payments_group on payments (group_id, paid_on);
