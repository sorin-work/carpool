create table swap_requests (
    id              bigint generated by default as identity primary key,
    ride_id         bigint      not null references rides (id) on delete cascade,
    requester_id    bigint      not null references group_members (id) on delete cascade,
    target_id       bigint      not null references group_members (id) on delete cascade,
    -- optional ride the requester takes over from the target in return
    offered_ride_id bigint references rides (id) on delete cascade,
    message         varchar(300),
    status          varchar(16) not null,
    created_at      timestamp with time zone not null,
    resolved_at     timestamp with time zone
);

create index ix_swap_requests_ride on swap_requests (ride_id);
create index ix_swap_requests_target on swap_requests (target_id, status);
