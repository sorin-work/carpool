-- One row per day a trip actually runs. Rows are created lazily when the
-- schedule for a date range is first read.
create table rides (
    id            bigint generated by default as identity primary key,
    trip_id       bigint      not null references trips (id) on delete cascade,
    ride_date     date        not null,
    departure_at  timestamp with time zone not null,
    driver_id     bigint references group_members (id) on delete set null,
    seats_offered integer     not null default 0,
    status        varchar(16) not null,
    cancel_reason varchar(300),
    created_at    timestamp with time zone not null,
    constraint uq_rides_trip_date unique (trip_id, ride_date)
);

create index ix_rides_departure on rides (departure_at);
